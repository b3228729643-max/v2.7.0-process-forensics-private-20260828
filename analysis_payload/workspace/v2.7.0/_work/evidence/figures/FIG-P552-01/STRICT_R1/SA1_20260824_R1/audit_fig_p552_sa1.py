def save_rgb(path: Path, arr: np.ndarray) -> None:
    Image.fromarray(arr, "RGB").save(path)


def save_gray(path: Path, arr: np.ndarray) -> None:
    Image.fromarray(arr, "L").save(path)


def save_nn8(path: Path, arr: np.ndarray, mode: str) -> None:
    """Inspection-only 8x nearest-neighbour view; never used for measurement."""
    im = Image.fromarray(arr, mode)
    im.resize((im.width * 8, im.height * 8), Image.Resampling.NEAREST).save(path)


def render_rgb(page: fitz.Page, clip: fitz.Rect, dpi: int) -> np.ndarray:
    pix = page.get_pixmap(matrix=fitz.Matrix(dpi / 72.0, dpi / 72.0), clip=clip, alpha=False)
    arr = np.frombuffer(pix.samples, dtype=np.uint8).reshape(pix.height, pix.width, pix.n)
    if pix.n == 4:
        arr = arr[:, :, :3]
    elif pix.n == 1:
        arr = np.repeat(arr[:, :, :1], 3, axis=2)
    return arr.copy()


def native_crop(full: np.ndarray, rect: fitz.Rect) -> np.ndarray:
    """Slice an already-native full-page 300 dpi grid; never resample."""
    x0, y0 = math.floor(rect.x0 * SCALE), math.floor(rect.y0 * SCALE)
    x1, y1 = math.ceil(rect.x1 * SCALE), math.ceil(rect.y1 * SCALE)
    return full[y0:y1, x0:x1].copy()


def foreground_mask(rgb: np.ndarray) -> np.ndarray:
    """Raw foreground from relative local background >=20/255, never dilated."""
    bg = cv2.medianBlur(rgb, 31)
    delta = np.abs(rgb.astype(np.int16) - bg.astype(np.int16)).max(axis=2)
    # Median can reproduce a large dark region.  The white-page fallback keeps
    # dark coloured vector/text ink while still preserving the >=20 criterion.
    page_delta = np.abs(rgb.astype(np.int16) - 255).max(axis=2)
    return ((delta >= 20) | (page_delta >= 20)).astype(np.uint8)


def pxbounds(rect: fitz.Rect, clip: fitz.Rect, shape: tuple[int, int]) -> tuple[int, int, int, int]:
    h, w = shape
    # Map through the same full-page native grid used for crop evidence.  This
    # makes raster coordinates invariant to a non-integral PDF clip origin.
    ox, oy = math.floor(clip.x0 * SCALE), math.floor(clip.y0 * SCALE)
    x0 = max(0, min(w, math.floor(rect.x0 * SCALE) - ox))
    y0 = max(0, min(h, math.floor(rect.y0 * SCALE) - oy))
    x1 = max(0, min(w, math.ceil(rect.x1 * SCALE) - ox))
    y1 = max(0, min(h, math.ceil(rect.y1 * SCALE) - oy))
    return x0, y0, x1, y1


def rect_distance_px(a: fitz.Rect, b: fitz.Rect) -> float:
    dx = max(a.x0 - b.x1, b.x0 - a.x1, 0.0) * SCALE
    dy = max(a.y0 - b.y1, b.y0 - a.y1, 0.0) * SCALE
    return math.hypot(dx, dy)


def mask_bbox(mask: np.ndarray) -> tuple[int, int, int, int] | None:
    ys, xs = np.where(mask > 0)
    if len(xs) == 0:
        return None
    return int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1


def mask_height(mask: np.ndarray) -> int:
    bb = mask_bbox(mask)
    return 0 if bb is None else bb[3] - bb[1]


def mask_distance(a: np.ndarray, b: np.ndarray) -> tuple[int, float]:
    """Exact raw-mask intersection and 1:1 pixel clearance, no morphology."""
    overlap = int(np.count_nonzero((a > 0) & (b > 0)))
    if overlap:
        return overlap, 0.0
    if not np.any(a) or not np.any(b):
        return overlap, float("inf")
    # cv2 distanceTransform gives distance from each zero pixel to the nearest
    # foreground in b; evaluate it on a's foreground only.
    dist = cv2.distanceTransform((b == 0).astype(np.uint8), cv2.DIST_L2, 5)
    return 0, float(dist[a > 0].min())


def distance_field(mask: np.ndarray) -> np.ndarray:
    """One raw-mask distance field, reused for all pairs against this mask."""
    return cv2.distanceTransform((mask == 0).astype(np.uint8), cv2.DIST_L2, 5)


def mask_distance_with_field(a: np.ndarray, b: np.ndarray, b_field: np.ndarray) -> tuple[int, float]:
    overlap = int(np.count_nonzero((a > 0) & (b > 0)))
    if overlap:
        return overlap, 0.0
    if not np.any(a) or not np.any(b):
        return overlap, float("inf")
    return 0, float(b_field[a > 0].min())


def local_crop(mask_a: np.ndarray, mask_b: np.ndarray, rgb: np.ndarray, pad: int = 24):
    ys, xs = np.where((mask_a > 0) | (mask_b > 0))
    if len(xs) == 0:
        return 0, 0, 1, 1
    x0 = max(0, int(xs.min()) - pad)
    x1 = min(rgb.shape[1], int(xs.max()) + 1 + pad)
    y0 = max(0, int(ys.min()) - pad)
    y1 = min(rgb.shape[0], int(ys.max()) + 1 + pad)
    return x0, y0, x1, y1


def char_class(c: str, is_script: bool) -> str:
    if is_script:
        return "NATURAL_SCRIPT"
    if c in "=+−-<>≠≤≥≈×÷∞[](){}|/":
        return "MATH_OPERATOR"
    # Fullwidth CJK punctuation is deliberately held to the fullwidth gate;
    # ASCII punctuation still receives its own semantic punctuation gate.
    cat = unicodedata.category(c)
    east = unicodedata.east_asian_width(c)
    if east in {"W", "F"} and c.strip():
        return "CJK_FULLWIDTH"
    if c.isdigit() or (len(c) == 1 and "A" <= c <= "Z"):
        return "UPPER_DIGIT"
    if c in "𝑖𝑗𝑘𝑡𝜏𝔼" or c.islower():
        return "LOWER_GREEK"
    if cat.startswith("P") or c in ",.:;，。：；…":
        return "PUNCTUATION"
    return "LOWER_GREEK"


def is_script_char(element_id: str, c: str, rect: fitz.Rect, all_rects: list[fitz.Rect], pdf_size_pt: float) -> bool:
    # Only TeX-generated superscript/subscript forms in tau_i / tau_i^+ count
    # as natural scripts.  A literal plus or i in a state node does not.
    if element_id in {"TOP_TITLE", "BOTTOM_TITLE", "TOP_INTERVAL", "BOTTOM_INTERVAL", "CONCLUSION", "CAPTION_PARENT"}:
        # A superscript plus is always the compact form in these formulae.  A
        # compact i is a subscript only when its PDF baseline is visibly lower
        # than the parent line; this preserves the base i in j≠i and prose.
        if c == "+" and pdf_size_pt < 9.5:
            return True
        baseline = statistics.median([q.y0 for q in all_rects]) if all_rects else rect.y0
        return c == "𝑖" and pdf_size_pt < 9.5 and rect.y0 > baseline + 2.0
    return False


