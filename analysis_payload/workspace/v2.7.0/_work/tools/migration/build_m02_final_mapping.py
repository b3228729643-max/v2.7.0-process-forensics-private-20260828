    if ordinal in MANUAL_KIND:
        kind = MANUAL_KIND[ordinal]
    if ordinal in MANUAL_CONTRACT:
        inputs, update, stopping = MANUAL_CONTRACT[ordinal]
        preconditions = preconditions or "输入满足声明的定义域与有限性条件"
