def raw_characters(page: fitz.Page) -> list[dict]:
    chars = []
    raw = page.get_text("rawdict")
    n = 0
    for block in raw["blocks"]:
        if block.get("type") != 0:
            continue
        for line in block["lines"]:
            for span in line["spans"]:
                for ch in span["chars"]:
                    r = fitz.Rect(ch["bbox"])
                    # retain only reader-visible chars in the figure/caption field
                    if r.x1 <= FIG_RECT.x0 or r.x0 >= FIG_RECT.x1 or r.y1 <= FIG_RECT.y0 or r.y0 >= FIG_RECT.y1:
                        continue
                    # The crop intentionally has a small white gutter above the
                    # first interval label.  Exclude the preceding body line
                    # which merely crosses that gutter by a sub-pixel amount.
                    if r.y0 < 609.0:
                        continue
                    if not ch["c"].strip():
                        continue
                    eid = assign_element(r, ch["c"])
                    if eid is None:
                        raise RuntimeError(f"unmapped visible figure char {ch['c']!r} bbox={tuple(r)}")
                    chars.append({
                        "char_index": n,
                        "c": ch["c"],
                        "rect": r,
                        "font": span.get("font", ""),
                        "pdf_size_pt": float(span.get("size", 0.0)),
                        "element_id": eid,
                    })
                    n += 1
    return chars


def reconstruct_vector_mask(page_rect: fitz.Rect, clip: fitz.Rect, draw: dict, dpi: int, include_fill: bool) -> np.ndarray:
    """Render one PDF drawing alone, so vector masks cannot be paint-order polluted."""
    d = fitz.open()
    p = d.new_page(width=page_rect.width, height=page_rect.height)
    s = p.new_shape()
    any_item = False
    for item in draw["items"]:
        typ = item[0]
        if typ == "l":
            s.draw_line(item[1], item[2]); any_item = True
        elif typ == "c":
            s.draw_bezier(item[1], item[2], item[3], item[4]); any_item = True
        elif typ == "re":
            s.draw_rect(item[1]); any_item = True
        elif typ == "qu":
            s.draw_quad(item[1]); any_item = True
        else:
            raise RuntimeError(f"unsupported drawing item {typ}")
    if not any_item:
        d.close()
        return np.zeros((int(round(clip.height*SCALE)), int(round(clip.width*SCALE))), dtype=np.uint8)
    color = (0.0, 0.0, 0.0) if draw.get("color") is not None else None
    fill = (0.0, 0.0, 0.0) if include_fill and draw.get("fill") is not None else None
    s.finish(
        width=float(draw.get("width") or 1.0), color=color, fill=fill,
        lineCap=1, lineJoin=1, dashes=draw.get("dashes") or "[] 0",
        closePath=bool(draw.get("closePath")),
        fill_opacity=float(draw.get("fill_opacity") or 1.0),
        stroke_opacity=float(draw.get("stroke_opacity") or 1.0),
        even_odd=bool(draw.get("even_odd")),
    )
    s.commit()
    # Render the isolated vector on the full native page grid before slicing.
    # It stays coordinate-identical to full_page_300dpi.png and avoids a clip
    # origin changing anti-alias placement by a pixel.
    pix = p.get_pixmap(matrix=fitz.Matrix(dpi / 72.0, dpi / 72.0), colorspace=fitz.csGRAY, alpha=False)
    arr = np.frombuffer(pix.samples, dtype=np.uint8).reshape(pix.height, pix.width)
    x0, y0 = math.floor(clip.x0 * SCALE), math.floor(clip.y0 * SCALE)
    x1, y1 = math.ceil(clip.x1 * SCALE), math.ceil(clip.y1 * SCALE)
    arr = arr[y0:y1, x0:x1]
    d.close()
    return (arr < 235).astype(np.uint8)


