def contract_question(
    title: str,
    object_name: str,
    inputs: str,
    preconditions: str,
    update: str,
    stopping: str,
    output: str,
) -> tuple[str, str, str, str]:
    def complete_clause(value: str, markers: tuple[str, ...] = ()) -> str:
        cleaned = strip_tex(value)
        clauses = split_outside_structures(cleaned, ("；", "。"))
        if markers:
            selected = next((piece for piece in clauses if any(marker in piece for marker in markers)), None)
            if selected:
                return selected
        return clauses[0] if clauses else cleaned

    def summarize_items(value: str, maximum: int = 3) -> str:
        pieces = split_outside_structures(value, ("、",))
        return "、".join(pieces)

    object_focus = object_name
    input_focus = summarize_items(complete_clause(inputs), 4)
    condition = complete_clause(preconditions)
    update_focus = complete_clause(update, ("原子提交", "提交", "更新", "追加", "替换", "合并"))
    stop_focus = complete_clause(stopping or output)
    if title.endswith("：执行契约"):
        question = (
            f"{object_focus}输入“{input_focus}”，条件“{condition}”；请执行“{update_focus}”，"
            f"以“{stop_focus}”判停。"
        )
        task = f"执行一次“{update_focus}”并检查提交门"
        expected = f"停止或提交判据“{stop_focus}”给出明确结论"
    else:
        question = (
            f"{object_focus}输入“{input_focus}”，条件“{condition}”；请做一轮“{update_focus}”，"
            f"以“{stop_focus}”核对停止证书。"
        )
        task = f"完成一轮“{update_focus}”"
        expected = f"停止证书与“{stop_focus}”一致"
    return question, condition, task, expected


def concrete_symbol_check(symbol: str) -> tuple[str, str]:
    """Choose one check implied by the actual mathematical token, not a menu."""
