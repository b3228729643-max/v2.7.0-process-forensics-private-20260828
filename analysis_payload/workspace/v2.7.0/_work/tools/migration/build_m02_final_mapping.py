def split_outside_structures(text: str, separators: tuple[str, ...]) -> list[str]:
    """Split only outside inline math, TeX groups, and Chinese quotations."""
    ordered = tuple(sorted(separators, key=len, reverse=True))
    pieces: list[str] = []
    buffer: list[str] = []
    in_math = False
    in_quote = False
    brace_depth = 0
    index = 0
    while index < len(text):
        char = text[index]
        escaped = index > 0 and text[index - 1] == "\\" and (
            index < 2 or text[index - 2] != "\\"
        )
        if char == "$" and not escaped:
            in_math = not in_math
            buffer.append(char)
            index += 1
            continue
        if not in_math:
            if char == "“":
                in_quote = True
            elif char == "”":
                in_quote = False
            elif char == "{":
                brace_depth += 1
            elif char == "}" and brace_depth:
                brace_depth -= 1
            if not in_quote and brace_depth == 0:
                separator = next((item for item in ordered if text.startswith(item, index)), None)
                if separator is not None:
                    piece = "".join(buffer).strip()
                    if piece:
                        pieces.append(piece)
                    buffer = []
                    index += len(separator)
                    continue
        buffer.append(char)
        index += 1
    piece = "".join(buffer).strip()
    if piece:
        pieces.append(piece)
    return pieces


def source_facts(lines: list[str]) -> list[str]:
    """Recover complete source sentences across arbitrary physical line wraps."""
    joined = " ".join(substantive_lines(lines))
    value = strip_tex(joined)
    return [
        piece.strip("，；。 ")
        for piece in split_outside_structures(value, ("。", "；", "？", "?", "！", "!"))
        if len(piece.strip("，；。 ")) >= 5
    ]


def find_environment_end(lines: list[str], start: int, cap: int) -> int:
    match = BEGIN_RE.match(lines[start].strip())
    if not match:
        return min(len(lines) - 1, start + cap)
    name = match.group("name")
    depth = 0
    for index in range(start, min(len(lines), start + cap + 1)):
        depth += len(re.findall(rf"\\begin\{{{re.escape(name)}\}}", lines[index]))
        depth -= len(re.findall(rf"\\end\{{{re.escape(name)}\}}", lines[index]))
        if depth == 0 and index > start:
            return index
    return min(len(lines) - 1, start + cap)


def special_anchor_start(lines: list[str], index: int, title: str) -> int | None:
    patterns: tuple[str, ...]
    if title.startswith("本章地图"):
        patterns = ("\\SLChapterOpening", "\\chapter{")
    elif title == "本章可检验学习目标":
        patterns = ("\\chaptergoals{",)
    elif title == "最短先修":
        patterns = ("\\begin{prerequisitebox}",)
    elif title == "先修自检":
        patterns = ("\\begin{precheckbox}", "\\begin{selfcheckbox}")
    elif title == "依赖路线":
        patterns = ("\\begin{dependencybox}",)
    elif title == "本章符号表":
        patterns = ("\\begin{symboltablebox}",)
    elif title == "本章结论与下一步":
        patterns = ("\\SLChapterFiveSummary",)
    else:
        return None
    for pattern in patterns:
        for probe in range(index + 1, min(len(lines), index + 90)):
            if pattern in lines[probe]:
                return probe
    return None


def proof_like(title: str, nearby: str) -> bool:
    if title.startswith("证明："):
        return True
    if any(word in title for word in PROOF_WORDS):
        return not any(token in title for token in ("算法的收敛性", "算法特性", "预测算法"))
    return False


def find_anchor(lines: list[str], index: int, title: str, chapter: str) -> tuple[int, int]:
    special = special_anchor_start(lines, index, title)
    if special is not None:
        if lines[special].lstrip().startswith("\\begin{"):
            return special, find_environment_end(lines, special, 36)
        if "\\SLChapterOpening" in lines[special]:
            return special, min(len(lines) - 1, special + 6)
        if "\\SLChapterFiveSummary" in lines[special]:
            return special, min(len(lines) - 1, special + 4)
        return special, min(len(lines) - 1, special + 22)

    nearby = "\n".join(lines[index + 1 : index + 16])
    if proof_like(title, nearby):
        for probe in range(index + 1, min(len(lines), index + 20)):
            if "\\begin{proof}" in lines[probe]:
                return probe, find_environment_end(lines, probe, 42)

    # Immediate pedagogical/contract boxes are stronger than a later name hit.
    for probe in range(index + 1, min(len(lines), index + 8)):
        line = lines[probe].strip()
        if line.startswith(
            (
                "\\begin{warningbox}",
                "\\begin{complexitybox}",
                "\\begin{applicabilitybox}",
                "\\begin{comparisonbox}",
                "\\begin{notapplicablebox}",
            )
        ):
            return probe, find_environment_end(lines, probe, 32)
        if "\\begin{keypointbox}" in line or "\\begin{AlgorithmContract}" in line:
            end = find_environment_end(lines, probe, 46)
            # The five-step reader box is followed by the real contract.
            for later in range(end + 1, min(len(lines), end + 10)):
                if "\\begin{AlgorithmContract}" in lines[later]:
                    end = find_environment_end(lines, later, 45)
                    break
            return probe, end
        # Generic environments can belong to the preceding stacked self-check.
        # Exact title/anchor matching below is safer for definitions, examples,
        # theorems and algorithms; only dedicated reader/contract boxes are
        # claimed eagerly here.

    core = core_title(title, chapter)
    candidates = [title, core]
    for prefix in PREFIXES:
        if title.startswith(prefix):
            candidates.append(title[len(prefix) :])
    candidates = [normalized(item.removesuffix("：执行契约")) for item in candidates]
    candidates = [item for item in candidates if len(item) >= 3]
    best: tuple[int, int] | None = None
    for probe in range(index + 1, min(len(lines), index + 180)):
        line = lines[probe]
        if line.startswith("\\paragraph{读前自检："):
            continue
        line_norm = normalized(line)
        if not line_norm:
            continue
        score = 0
        if "\\knowledgeanchor" in line:
            score += 80
        if "\\begin{" in line or "\\textbf{" in line or "\\SL" in line:
            score += 25
        if any(candidate in line_norm or line_norm in candidate for candidate in candidates):
            score += 60
        if score and (best is None or score > best[0]):
            best = (score, probe)
            if score >= 140:
                break
    if best is not None:
        start = best[1]
        if "\\knowledgeanchor" in lines[start]:
            end = min(len(lines) - 1, start + 48)
            substantive_seen = False
            for probe in range(start + 1, end + 1):
                current = lines[probe].strip()
                is_boundary = current.startswith(
                    (
                        "\\knowledgeanchor",
                        "\\subsection",
                        "\\section",
                        "\\paragraph{读前自检：",
                    )
                )
                if substantive_seen and is_boundary:
                    end = probe - 1
                    break
                if not substantive_seen and is_boundary:
                    continue
                if not substantive_seen and substantive_lines([current]):
                    substantive_seen = True
            return start, max(start, end)
        begin = next(
            (probe for probe in range(start, min(len(lines), start + 4)) if BEGIN_RE.match(lines[probe].strip())),
            None,
        )
        if begin is not None:
            return start, find_environment_end(lines, begin, 40)
        end = min(len(lines) - 1, start + 72)
        substantive_seen = 0
        for probe in range(start + 1, end + 1):
            current = lines[probe].strip()
            if current and not current.startswith(("%", "\\knowledgeanchor", "\\index", "\\phantomsection", "\\label")):
                if not re.fullmatch(r"\\(?:begin|end)\{[^}]+\}.*", current):
                    substantive_seen += 1
            if substantive_seen >= 2 and (
                lines[probe].startswith("\\paragraph{读前自检：")
                or re.match(r"\\SL\w+Section", lines[probe])
            ):
                end = probe - 1
                break
            if substantive_seen >= 12:
                end = probe
                break
        return start, end

    start = index + 1
    while start < len(lines) and (not lines[start].strip() or lines[start].lstrip().startswith("%")):
        start += 1
    if start >= len(lines):
        return index, index
    if BEGIN_RE.match(lines[start].strip()):
        return start, find_environment_end(lines, start, 36)
    return start, min(len(lines) - 1, start + 14)


def inline_math(text: str) -> list[str]:
    values: list[str] = []
    for match in INLINE_MATH_RE.finditer(text):
        token = "$" + match.group(1).strip() + "$"
        if len(token) > 120 or any(bad in token for bad in ("\\cref", "\\GlobalChapterRef")):
            continue
        if token not in values:
            values.append(token)
    return values


def display_math(lines: list[str]) -> list[str]:
    values: list[str] = []
    collecting = False
    buffer: list[str] = []
    for raw in lines:
        line = raw.strip()
        if line == "\\[" or re.match(r"\\begin\{(?:equation\*?|align\*?|aligned)\}", line):
            collecting = True
            buffer = []
            continue
        if collecting and (line == "\\]" or re.match(r"\\end\{(?:equation\*?|align\*?|aligned)\}", line)):
            value = " ".join(buffer)
            value = re.sub(r"\\label\{[^}]+\}", "", value)
            value = re.sub(r"\s+", " ", value).strip()
            if value and len(value) <= 120:
                token = "$" + value + "$"
                if token not in values:
                    values.append(token)
            collecting = False
            buffer = []
            continue
        if collecting:
            if line and not line.startswith("%"):
                buffer.append(line)
    return values


def field_value(lines: list[str], name: str) -> str | None:
    pattern = re.compile(rf"\b{re.escape(name)}=\{{(?P<value>.*)\}},?\s*$")
    for line in lines:
        match = pattern.search(line.strip())
        if match:
            return match.group("value").strip()
    return None


def command_value(lines: list[str], command: str) -> str | None:
    prefix = "\\" + command
    for line in lines:
        stripped = line.strip()
        if stripped.startswith(prefix):
            groups = balanced_groups(stripped[len(prefix) :])
            if groups:
                return strip_tex(groups[0])
    return None


def fact_with_marker(lines: list[str], markers: tuple[str, ...]) -> str | None:
    for value in source_facts(lines):
        if any(marker in value for marker in markers):
            return value
    return None


def first_fact(lines: list[str], markers: tuple[str, ...] = ()) -> str:
    candidates = source_facts(lines)
    for value in candidates:
        if value.startswith(("输入。", "初始化。", "核心更新。", "数学停止。", "输出。")):
            continue
        if markers and any(marker in value for marker in markers):
            return value
    return candidates[0] if candidates else "按所列定义与条件"


def last_fact(lines: list[str], markers: tuple[str, ...] = ()) -> str:
    candidates = source_facts(lines)
    for value in reversed(candidates):
        if markers and any(marker in value for marker in markers):
            return value
    return candidates[-1] if candidates else "结果满足紧随其后的定义域与结论"


def safe_clip(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    pieces = re.split(r"(\$[^$]*\$)", text)
    kept = ""
    for piece in pieces:
        if not piece:
            continue
        if piece.startswith("$") and piece.endswith("$"):
            shortened = short_math(piece)
            if len(shortened) < len(piece):
                piece = shortened
            if len(kept) + len(piece) > limit:
                if len(kept) <= 8:
                    kept += piece
                break
            kept += piece
            continue
        remaining = limit - len(kept)
        if remaining <= 0:
            break
        if kept and remaining < 8:
            break
        if len(piece) <= remaining:
            kept += piece
            continue
        fragment = piece[:remaining]
        cut = max(fragment.rfind(mark) for mark in ("，", "；", "、", ",", ";"))
        if cut >= max(8, remaining // 2):
            fragment = fragment[:cut]
        kept += fragment
        break
    return kept.rstrip("，,；;、 ")


def compact_clause(text: str, limit: int = 62) -> str:
    value = strip_tex(text)
    # A precheck question often has the form “若/给定 …，能否 …？”.  The
    # comma separates its condition from its required action, so retaining
    # only the left half makes the task impossible.
    if "能否" in value or "是否" in value:
        return value
    for separator in ("。", "；", "\\par"):
        pieces = split_outside_structures(value, (separator,))
        if len(pieces) > 1:
            value = pieces[0]
            if len(value) < 8:
                value = pieces[1]
            break
    if len(value) <= limit:
        return value
    # Never cut a Chinese phrase or a LaTeX token at an arbitrary character.
    # Prefer a complete leading clause; if even that clause is long, retain it
    # intact and let the caller decide whether the mathematically necessary
    # detail justifies a long question.
    for separator in ("；", "，", ","):
        pieces = split_outside_structures(value, (separator,))
        if len(pieces) <= 1:
            continue
        kept: list[str] = []
        for piece in pieces:
            candidate = separator.join(kept + [piece])
            if kept and len(candidate) > limit:
                break
            kept.append(piece)
            if len(candidate) >= max(12, limit // 2):
                break
        if kept:
            return separator.join(kept)
    return value


def focus_clause(text: str, markers: tuple[str, ...], limit: int) -> str:
    value = strip_tex(text)
    clauses = split_outside_structures(value, ("；", "。"))
    chosen = next((piece for piece in clauses if any(marker in piece for marker in markers)), None)
    return compact_clause(chosen or value, limit)


def clean_clause(text: str) -> bool:
    """Reject editorial macros, dangling math and clipped source fragments."""
    value = text.strip()
    if not value or value in {"按所列定义与条件", "结果满足紧随其后的定义域与结论"}:
        return False
    if value.count("$") % 2:
        return False
    if any(token in value for token in ("\\SL", "\\Sol", "\\Needspace", "\\begin", "\\end")):
        return False
    outside_math = re.sub(r"\$[^$]*\$", "", value)
    if "\\" in outside_math:
        return False
    if value.rstrip().endswith(
        (
            "为", "则", "得到", "如下", "定义为", "等于", "的", "到", "且", "与", "和", "或", "把", "从", "在", "若", "对",
            "并", "故", "所以", "任意", "所有", "满足", "其中", "步骤", "第", "：", "=", "(", "{",
        )
    ):
        return False
    return True


def informative_math(maths: list[str]) -> str | None:
    if not maths:
        return None
    substantive = [
        token for token in maths
        if len(token) >= 8
        or any(mark in token for mark in ("=", "<", ">", "\\le", "\\ge", "\\in", "\\sum", "\\int", "\\to", "\\subset"))
    ]
    if not substantive:
        return None
    ranked = sorted(
        enumerate(substantive),
        key=lambda item: (
            any(mark in item[1] for mark in ("=", "\\le", "\\ge", "\\in", "\\sum", "\\int")),
            len(item[1]) >= 8,
            min(len(item[1]), 120),
            -item[0],
        ),
        reverse=True,
    )
    return ranked[0][1]


def comparison_first_row(lines: list[str]) -> list[str]:
    """Return the first body row of a comparison table, never the header."""
    raw = " ".join(lines)
    if "\\midrule" in raw:
        raw = raw.split("\\midrule", 1)[1]
    if "\\bottomrule" in raw:
        raw = raw.split("\\bottomrule", 1)[0]
    rows = [row.strip() for row in re.split(r"\\\\", raw) if row.strip()]
    for row in rows:
        cells = [strip_tex(cell).strip("，；。 ") for cell in re.split(r"(?<!\\)&", row)]
        cells = [cell for cell in cells if cell and cell not in {"\\toprule", "\\midrule", "\\bottomrule"}]
        if len(cells) >= 2:
            return cells
    return []


def condition_and_conclusion(text: str) -> tuple[str, str]:
    value = strip_tex(text)
    # Only treat an explicit clause boundary as implication.  A bare ``则``
    # or ``满足`` also occurs inside complete words such as 否则、正则、规则、
    # 准则 and 不满足; splitting on those substrings created the reviewed
    # fragments “否”“正”“规” and “任何不”.
    for marker in ("，则", "；则", "，故", "；故", "，因此", "；因此", "；于是", "，于是", "并有"):
        if marker in value:
            left, right = value.split(marker, 1)
            if len(left.strip()) >= 3 and len(right.strip()) >= 3:
                return left.strip("，； "), right.strip("，； ")
    leading = re.match(r"^若(?P<left>.+?)则(?P<right>.+)$", value)
    if leading and all(token not in leading.group("left")[-2:] for token in ("否", "正", "规", "准", "原")):
        left = leading.group("left").strip("，； ")
        right = leading.group("right").strip("，； ")
        if len(left) >= 3 and len(right) >= 3:
            return left, right
    return value, value


def short_math(token: str) -> str:
    if len(token) <= 42:
        return token
    body = token[1:-1]
    split_at = -1
    braces = brackets = parentheses = 0
    escaped = False
    for index, char in enumerate(body):
        if escaped:
            escaped = False
            continue
        if char == "\\":
            escaped = True
            continue
        if char == "{":
            braces += 1
        elif char == "}":
            braces = max(0, braces - 1)
        elif char == "[":
            brackets += 1
        elif char == "]":
            brackets = max(0, brackets - 1)
        elif char == "(":
            parentheses += 1
        elif char == ")":
            parentheses = max(0, parentheses - 1)
        elif char == "=" and braces == brackets == parentheses == 0:
            split_at = index
            break
    if split_at >= 0:
        left = body[:split_at].strip()
        if left and len(left) <= 70 and left.count("{") == left.count("}"):
            return "$" + left + "$"
    for delimiter in (r"\quad\text{s.t.}", r"\qquad", r"\quad"):
        if delimiter in body:
            left = body.split(delimiter, 1)[0].strip()
            if left and len(left) <= 78 and left.count("{") == left.count("}"):
                return "$" + left + "$"
    # Keeping a complete formula is preferable to cutting through a nested
    # subscript or command argument and producing invalid LaTeX.
    return token


