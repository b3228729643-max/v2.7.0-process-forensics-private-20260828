def core_title(title: str, chapter: str) -> str:
    value = title.strip()
    for prefix in PREFIXES:
        if value.startswith(prefix):
            value = value[len(prefix) :].strip()
            break
    value = value.removesuffix("：执行契约").strip()
    if value in {"本章地图：算法", "算法", "本章地图"}:
        return chapter
    if value in SPECIAL_KIND or value == "范围说明":
        return f"{chapter}{value}"
    if len(strip_tex(value)) < 5:
        return f"{chapter}中的{value}"
    return value


def strip_tex(text: str) -> str:
    value = text
    value = re.sub(r"%.*", "", value)
    value = value.replace(r"\&", "与").replace("&", "、")
    value = re.sub(r"\\(?:phantomsection|small|toprule|midrule|bottomrule)\b", "", value)
    value = re.sub(r"\\GlobalChapterRef\{[^{}]*\}\{[^{}]*\}\{[^{}]*\}", "所引章节", value)
    value = re.sub(r"\\(?:eqref|ref|cref)\{[^{}]*\}", "相应公式", value)
    value = re.sub(r"\\(?:label|index)\{[^{}]*\}", "", value)
    value = re.sub(r"\\knowledgeanchor\{[^{}]*\}\{([^{}]*)\}", r"\1", value)
    value = re.sub(r"\\begin\{[^{}]*\}|\\end\{[^{}]*\}", "", value)
    value = re.sub(r"\\textbf\{([^{}]*)\}", r"\1", value)
    value = re.sub(r"\\(?:paragraph|SL\w+Section)\{([^{}]*)\}", r"\1", value)
    value = re.sub(r"\\item\b", "", value)
    value = re.sub(r"\\par\b", " ", value).replace(r"\\", " ")
    value = re.sub(r"\s+", " ", value)
    value = value.replace("定理相应公式", "该定理").replace("命题相应公式", "该命题")
    value = value.replace("图相应公式", "图中关系").replace("式相应公式", "该等式")
    value = value.replace("相应公式", "所列关系")
    value = value.replace("这里的", "当前定义中的").replace("这里", "当前定义")
    return value.strip(" {}，；。")


def normalized(text: str) -> str:
    value = strip_tex(text)
    value = re.sub(r"[\s：:，,。；;（）()\-—–·/_^\\{}$]", "", value)
    return value.lower()


def balanced_groups(text: str) -> list[str]:
    groups: list[str] = []
    depth = 0
    start = -1
    escaped = False
    for index, char in enumerate(text):
        if escaped:
            escaped = False
            continue
        if char == "\\":
            escaped = True
            continue
        if char == "{":
            if depth == 0:
                start = index + 1
            depth += 1
        elif char == "}" and depth:
            depth -= 1
            if depth == 0 and start >= 0:
                groups.append(text[start:index])
    return groups


def semantic_lines(lines: list[str], start: int, end: int) -> list[tuple[int, str]]:
    result: list[tuple[int, str]] = []
    for index in range(start, min(end + 1, len(lines))):
        line = lines[index].strip()
        if not line or line.startswith("%"):
            continue
        if line in {"\\[", "\\]"}:
            continue
        if re.fullmatch(r"\\(?:begin|end)\{[^}]+\}.*", line):
            continue
        if re.fullmatch(r"\\(?:phantomsection|label)\{[^}]+\}", line):
            continue
        if line.startswith("\\paragraph{读前自检："):
            continue
        result.append((index, line))
    return result


